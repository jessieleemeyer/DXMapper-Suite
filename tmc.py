def event_text(code):
    """Human phrase for an ALERT-C event code (quantifier markers removed)."""
    phrase = EVENTS.get(code)
    if phrase is None:
        return f"Event {code}"
    for marker in ("(Q sets of) ", "(Q) ", " (Q)", "{Q}", "(Q)"):
        phrase = phrase.replace(marker, "")
    phrase = phrase.replace("(s)", "s").replace("(y/ies)", "ies").replace("(a/Q) ", "")
    return phrase.strip().capitalize()


def decode_system_info(b3_val):
    """3A block 3 for AID 0xCD46: location table number and service flags."""
    variant = (b3_val >> 14) & 0x3
    if variant == 0:
        return {
            "variant": 0,
            "ltn": (b3_val >> 6) & 0x3F,
            "afi": bool((b3_val >> 5) & 0x1),
            "mode": (b3_val >> 4) & 0x1,
            "international": bool((b3_val >> 3) & 0x1),
            "national": bool((b3_val >> 2) & 0x1),
            "regional": bool((b3_val >> 1) & 0x1),
            "urban": bool(b3_val & 0x1),
        }
    if variant == 1:
        return {
            "variant": 1,
            "gap": (b3_val >> 12) & 0x3,
            "sid": (b3_val >> 6) & 0x3F,
            "activity_time": (b3_val >> 4) & 0x3,
            "window_time": (b3_val >> 2) & 0x3,
            "delay_time": b3_val & 0x3,
        }
    return {"variant": variant}


def decode_group(b2_val, b3_val, b4_val):
    """Decode one 8A group. Returns a dict with a 'kind' key:

    'single'  - complete single-group user message
    'first'   - first group of a multi-group message (event/location present)
    'next'    - continuation group (free-format bits)
    'tuning'  - tuning/service information
    """
    x4 = (b2_val >> 4) & 0x1
    x3 = (b2_val >> 3) & 0x1
    x210 = b2_val & 0x7
    if x4:
        return {"kind": "tuning", "variant": x210, "b3": b3_val, "b4": b4_val}
    if x3:
        return {
            "kind": "single",
            "duration": x210,
            "diversion": bool((b3_val >> 15) & 0x1),
            "direction": (b3_val >> 14) & 0x1,
            "extent": (b3_val >> 11) & 0x7,
            "event": b3_val & 0x7FF,
            "location": b4_val,
        }
    # multi-group: X2..X0 is the continuity index; block 3 bit 15 tells
    # whether this is the first group (1) or a following group (0).
    ci = x210
    first_flag = (b3_val >> 15) & 0x1
    if first_flag:
        return {
            "kind": "first",
            "ci": ci,
            "diversion": False,
            "direction": (b3_val >> 14) & 0x1,
            "extent": (b3_val >> 11) & 0x7,
            "event": b3_val & 0x7FF,
            "location": b4_val,
        }
    return {
        "kind": "next",
        "ci": ci,
        "second_group": bool((b3_val >> 14) & 0x1),
        "gsi": (b3_val >> 12) & 0x3,
        "free": ((b3_val & 0xFFF) << 16) | b4_val,
    }


def message_key(msg):
    return (msg["event"], msg["location"], msg["direction"], msg["extent"])


def format_message(msg):
    """One-line summary for GUI/report."""
    parts = [event_text(msg["event"])]
    parts.append(f"loc {msg['location']}")
    if msg.get("extent"):
        parts.append(f"+{msg['extent']}")
    parts.append("neg" if msg["direction"] else "pos")
    if msg.get("duration") is not None:
        parts.append(DURATIONS.get(msg["duration"], ""))
    if msg.get("diversion"):
        parts.append("diversion advised")
    if msg.get("kind") == "first":
        parts.append(f"multi-group{' +' + str(msg['extra_groups']) if msg.get('extra_groups') else ''}")
    return " | ".join(p for p in parts if p)
